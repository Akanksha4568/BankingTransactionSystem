package com.banking.model;

import java.math.BigDecimal; //to avoid floating-point precision errors
import java.time.LocalDateTime;

public class BankTransaction {

    private Long transactionId;
    private String idempotencyKey;  //Prevents the same transaction from being processed twice
    private Long fromAccountId;  //Account from which money is deducted
    private Long toAccountId;  //Account receiving money
    private String transactionType;  //DEPOSIT, WITHDRAWAL or TRANSFER
    private BigDecimal amount;  //Transaction amount
    private String status;  //PENDING, SUCCESS, FAILED or REJECTED
    private String description;
    private LocalDateTime createdAt;

    public BankTransaction() {
    }

    public Long getTransactionId() {
        return transactionId;
    }

    public void setTransactionId(Long transactionId) {
        this.transactionId = transactionId;
    }

    public String getIdempotencyKey() {
        return idempotencyKey;
    }

    public void setIdempotencyKey(String idempotencyKey) {
        this.idempotencyKey = idempotencyKey;
    }

    public Long getFromAccountId() {
        return fromAccountId;
    }

    public void setFromAccountId(Long fromAccountId) {
        this.fromAccountId = fromAccountId;
    }

    public Long getToAccountId() {
        return toAccountId;
    }

    public void setToAccountId(Long toAccountId) {
        this.toAccountId = toAccountId;
    }

    public String getTransactionType() {
        return transactionType;
    }

    public void setTransactionType(String transactionType) {
        this.transactionType = transactionType;
    }

    public BigDecimal getAmount() {
        return amount;
    }

    public void setAmount(BigDecimal amount) {
        this.amount = amount;
    }

    public String getStatus() {
        return status;
    }

    public void setStatus(String status) {
        this.status = status;
    }

    public String getDescription() {
        return description;
    }

    public void setDescription(String description) {
        this.description = description;
    }

    public LocalDateTime getCreatedAt() {
        return createdAt;
    }

    public void setCreatedAt(LocalDateTime createdAt) {
        this.createdAt = createdAt;
    }
}